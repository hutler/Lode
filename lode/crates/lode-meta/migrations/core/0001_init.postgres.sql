-- Postgres form of 0001_init.sql (T153): BIGINT for every integer, BYTEA for blobs, identity
-- columns for row ids, and the C collation so text sorts by bytes as in SQLite.
-- Core schema, ARCHITECTURE §4.2. Times are milliseconds since the Unix epoch, UTC.

CREATE TABLE depot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT COLLATE "C" NOT NULL UNIQUE,
    next_rev    BIGINT NOT NULL,
    created_at  BIGINT NOT NULL
);

CREATE TABLE principal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind           TEXT COLLATE "C" NOT NULL CHECK (kind IN ('user', 'agent')),
    name           TEXT COLLATE "C" NOT NULL UNIQUE,
    display_name   TEXT COLLATE "C",
    owner_id       BIGINT REFERENCES principal (id),
    password_hash  TEXT COLLATE "C",
    disabled       BIGINT NOT NULL DEFAULT 0,
    created_at     BIGINT NOT NULL
);

CREATE TABLE grp (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  TEXT COLLATE "C" NOT NULL UNIQUE
);

CREATE TABLE grp_member (
    grp_id        BIGINT NOT NULL REFERENCES grp (id) ON DELETE CASCADE,
    principal_id  BIGINT NOT NULL REFERENCES principal (id) ON DELETE CASCADE,
    PRIMARY KEY (grp_id, principal_id)
);

CREATE TABLE token (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal_id  BIGINT NOT NULL REFERENCES principal (id) ON DELETE CASCADE,
    name          TEXT COLLATE "C" NOT NULL,
    hash          BYTEA   NOT NULL UNIQUE,
    scopes        TEXT COLLATE "C" NOT NULL,
    expires_at    BIGINT,
    last_used_at  BIGINT,
    created_at    BIGINT NOT NULL
);

CREATE TABLE acl (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depot_id      BIGINT REFERENCES depot (id),
    subject_kind  TEXT COLLATE "C" NOT NULL CHECK (subject_kind IN ('all', 'user', 'group')),
    subject_id    BIGINT,
    branch_glob   TEXT COLLATE "C" NOT NULL,
    path_glob     TEXT COLLATE "C" NOT NULL,
    effect        TEXT COLLATE "C" NOT NULL CHECK (effect IN ('allow', 'deny')),
    level         TEXT COLLATE "C" NOT NULL CHECK (level IN ('read', 'write', 'admin'))
);

CREATE TABLE branch (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depot_id          BIGINT NOT NULL REFERENCES depot (id),
    name              TEXT COLLATE "C" NOT NULL,
    head_rev          BIGINT NOT NULL,
    created_rev       BIGINT NOT NULL,
    parent_branch_id  BIGINT REFERENCES branch (id),
    parent_rev        BIGINT,
    state             TEXT COLLATE "C" NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'archived')),
    UNIQUE (depot_id, name)
);

CREATE TABLE revision (
    depot_id      BIGINT NOT NULL REFERENCES depot (id),
    num           BIGINT NOT NULL,
    branch_id     BIGINT NOT NULL REFERENCES branch (id),
    parent_num    BIGINT,
    root_tree     BYTEA   NOT NULL,
    author_id     BIGINT NOT NULL REFERENCES principal (id),
    submitter_id  BIGINT NOT NULL REFERENCES principal (id),
    created_at    BIGINT NOT NULL,
    message       TEXT COLLATE "C" NOT NULL,
    provenance    TEXT COLLATE "C",
    request_id    TEXT COLLATE "C",
    PRIMARY KEY (depot_id, num),
    UNIQUE (depot_id, request_id)
);

CREATE TABLE rev_change (
    depot_id        BIGINT NOT NULL,
    rev             BIGINT NOT NULL,
    path            TEXT COLLATE "C" NOT NULL,
    action          TEXT COLLATE "C" NOT NULL CHECK (action IN ('A', 'M', 'D')),
    kind            BIGINT,
    old_id          BYTEA,
    new_id          BYTEA,
    size            BIGINT,
    flags           BIGINT NOT NULL DEFAULT 0,
    copy_from_path  TEXT COLLATE "C",
    copy_from_rev   BIGINT,
    PRIMARY KEY (depot_id, rev, path),
    FOREIGN KEY (depot_id, rev) REFERENCES revision (depot_id, num)
);

CREATE INDEX rev_change_path ON rev_change (depot_id, path, rev);

CREATE TABLE rev_merge (
    rowid             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depot_id          BIGINT NOT NULL,
    rev               BIGINT NOT NULL,
    source_branch_id  BIGINT NOT NULL REFERENCES branch (id),
    from_rev          BIGINT NOT NULL,
    to_rev            BIGINT NOT NULL,
    FOREIGN KEY (depot_id, rev) REFERENCES revision (depot_id, num)
);

CREATE TABLE rev_meta (
    depot_id  BIGINT NOT NULL,
    rev       BIGINT NOT NULL,
    key       TEXT COLLATE "C" NOT NULL,
    value     TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (depot_id, rev, key),
    FOREIGN KEY (depot_id, rev) REFERENCES revision (depot_id, num)
);

CREATE TABLE outbox (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depot_id    BIGINT,
    kind        TEXT COLLATE "C" NOT NULL,
    payload     TEXT COLLATE "C" NOT NULL,
    created_at  BIGINT NOT NULL
);

CREATE TABLE outbox_cursor (
    subscriber  TEXT COLLATE "C" PRIMARY KEY,
    last_id     BIGINT NOT NULL
);
